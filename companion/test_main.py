"""Tests for companion.main.run: one poll cycle over a fake WoW tree."""
import io
import json
import shutil
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path

from companion.main import run, char_key

SV_TEXT = (
    "DecadesSyncDB = {\n"
    '\t["core"] = {\n'
    '\t\t["name"] = "Grukk",\n'
    '\t\t["realm"] = "Decades",\n'
    '\t\t["class"] = "WARRIOR",\n'
    '\t\t["level"] = 60,\n'
    '\t},\n'
    '\t["pos"] = {\n'
    '\t\t["home"] = "Orgrimmar",\n'
    '\t},\n'
    "}\n"
)


class FakeWow:
    """A temp WoW install: SV file + addon dir + companion.toml."""

    def __init__(self, tmp: Path, ingest_url: str = "") -> None:
        self.root = tmp / "WoW"
        sv_dir = self.root / "WTF" / "Account" / "ACC" / "SavedVariables"
        sv_dir.mkdir(parents=True)
        self.sv = sv_dir / "DecadesSync.lua"
        self.sv.write_text(SV_TEXT, encoding="utf-8")
        (self.root / "Interface" / "AddOns" / "DecadesSync").mkdir(parents=True)
        self.config = tmp / "companion.toml"
        # TOML literal strings (single quotes): Windows backslashes stay raw.
        self.config.write_text(
            f"wow_root = '{self.root}'\n"
            "poll_seconds = 2.0\n"
            f"ingest_url = '{ingest_url}'\n",
            encoding="utf-8",
        )
        self.store_dir = tmp / "store"
        self.data_lua = (
            self.root / "Interface" / "AddOns" / "DecadesSync" / "Data" / "DecadesData.lua"
        )


class TestCharKey(unittest.TestCase):
    def test_name_realm_lowercased(self):
        sv = {"core": {"name": "Grukk", "realm": "Decades"}}
        self.assertEqual(char_key(sv), "grukk-decades")

    def test_fallback_unknown(self):
        self.assertEqual(char_key({}), "unknown")
        self.assertEqual(char_key({"core": {}}), "unknown")
        self.assertEqual(char_key({"core": {"realm": "Decades"}}), "unknown")


class TestRun(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="decades_main_"))
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.fake = FakeWow(self.tmp)

    def test_first_run_stores_and_emits(self):
        out = io.StringIO()
        with redirect_stdout(out):
            key = run(self.fake.config, once=True)
        self.assertEqual(key, "grukk-decades")
        snap = self.fake.store_dir / "grukk-decades" / "0001.json"
        self.assertTrue(snap.is_file(), f"missing {snap}")
        saved = json.loads(snap.read_text(encoding="utf-8"))
        self.assertEqual(saved["core"]["name"], "Grukk")
        self.assertTrue(self.fake.data_lua.is_file(), "Data.lua not written")
        text = self.fake.data_lua.read_text(encoding="utf-8")
        self.assertTrue(text.startswith("-- Generated by decades-companion. DO NOT EDIT."))
        self.assertIn("upload skipped (offline stub)", out.getvalue())

    def test_second_run_without_change_is_noop(self):
        self.assertIsNotNone(run(self.fake.config, once=True))
        out = io.StringIO()
        with redirect_stdout(out):
            key = run(self.fake.config, once=True)
        self.assertIsNone(key)
        files = list((self.fake.store_dir / "grukk-decades").glob("*.json"))
        self.assertEqual(len(files), 1)

    def test_new_change_appends_next_snapshot(self):
        run(self.fake.config, once=True)
        self.fake.sv.write_text(
            SV_text_level(61), encoding="utf-8"
        )
        key = run(self.fake.config, once=True)
        self.assertEqual(key, "grukk-decades")
        files = sorted((self.fake.store_dir / "grukk-decades").glob("*.json"))
        self.assertEqual([f.name for f in files], ["0001.json", "0002.json"])

    def test_ingest_url_set_raises_plan_b(self):
        fake = FakeWow(self.tmp / "remote", ingest_url="https://ingest.example.com/decades")
        with self.assertRaises(NotImplementedError):
            run(fake.config, once=True)


def SV_text_level(level: int) -> str:
    return SV_TEXT.replace('["level"] = 60', f'["level"] = {level}')


if __name__ == "__main__":
    unittest.main()
