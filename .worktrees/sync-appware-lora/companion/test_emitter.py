"""Tests for companion.emitter: Data.lua emission round-trips through svparse."""

import tempfile
import unittest
from pathlib import Path

from companion.emitter import emit_data_lua
from companion.svparse import parse_sv

HEADER = "-- Generated by decades-companion. DO NOT EDIT."


class TestEmitDataLua(unittest.TestCase):
    def test_round_trip_through_svparse(self):
        data = {"a": 1, "b": {"c": "x", "d": None, "e": True}}
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "DecadesData.lua"
            emit_data_lua(data, out)
            text = out.read_text(encoding="utf-8")
            lines = text.splitlines()
            self.assertEqual(lines[0], HEADER)
            body = "\n".join(lines[1:])
            self.assertTrue(body.lstrip().startswith("DecadesData"))
            self.assertEqual(parse_sv(body), data)

    def test_first_line_is_do_not_edit_comment(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "nested" / "Data" / "DecadesData.lua"
            emit_data_lua({"k": "v"}, out)
            self.assertTrue(out.exists(), "parent dirs must be created")
            self.assertEqual(
                out.read_text(encoding="utf-8").splitlines()[0], HEADER)

    def test_creates_parent_dirs_and_leaves_no_tmp(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "Interface" / "AddOns" / "DecadesSync" / "Data" / "DecadesData.lua"
            emit_data_lua({"generatedAt": "2026-09-28T00:00:00"}, out)
            self.assertTrue(out.is_file())
            self.assertEqual(sorted(p.name for p in out.parent.iterdir()),
                             ["DecadesData.lua"])

    def test_escapes_numbers_and_empty_table_round_trip(self):
        data = {"s": 'a"b\\c\nd', "f": 2.5, "neg": -1.5, "no": False,
                "empty": {}, "deep": {"inner": {"x": 0}}}
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "DecadesData.lua"
            emit_data_lua(data, out)
            body = "\n".join(
                out.read_text(encoding="utf-8").splitlines()[1:])
            self.assertEqual(parse_sv(body), data)

    def test_rejects_unsupported_value_type(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "DecadesData.lua"
            with self.assertRaises(TypeError):
                emit_data_lua({"bad": {1, 2}}, out)  # sets have never been supported
            self.assertFalse(out.exists())

    def test_list_round_trip(self):
        data = {"generatedAt": "t", "roster": [{"name": "Grukk"}, {"name": "Ulu"}], "nums": [1, 2, 3]}
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "Data" / "DecadesData.lua"
            emit_data_lua(data, out)
            body = "\n".join(l for l in out.read_text().splitlines() if not l.startswith("--"))
            self.assertEqual(parse_sv(body), data)

if __name__ == "__main__":
    unittest.main()
